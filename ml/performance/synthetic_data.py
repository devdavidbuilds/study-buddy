"""SYNTHETIC demonstration data for the performance model.

!!! These rows are generated by a formula below. They are NOT real Study
!!! Buddy students. A model trained on them only shows that the software
!!! works; its accuracy says nothing about real students.

Why it exists: on 2026-10-21 the Study Buddy database had 0 quiz attempts and
1 lesson check in total, so there is no real history to learn from yet.

How rows are made (one row = one upcoming quiz):
    ability          hidden student skill ~ Normal(65, 15), clipped to 0-100
    prev_attempts    Poisson(4), capped at 20
    prev_quiz_avg    ability + noise that shrinks with more attempts (empty if 0)
    last_quiz_score  ability + noise (empty if 0 attempts)
    completion_pct   Beta(2, 2) x 100, nudged up for stronger students
    target_score     0.75*ability + 0.15*completion + 0.6*min(attempts, 10) + noise
The model can never see `ability`; it has to infer it from the history
features, just as it would for real students.
"""

from __future__ import annotations

import csv
from pathlib import Path

import numpy as np

SYNTHETIC_CSV = Path(__file__).resolve().parent / "data" / "SYNTHETIC_demo_dataset.csv"
COLUMNS = ("student", "prev_quiz_avg", "prev_attempts", "completion_pct", "last_quiz_score", "target_score", "source")


def generate(n_rows: int = 600, seed: int = 7) -> tuple[list[dict], list[float], list[str]]:
    """Return (feature rows, target scores, student groups), all synthetic."""
    rng = np.random.default_rng(seed)
    clip = lambda values: np.clip(values, 0, 100)  # noqa: E731

    ability = clip(rng.normal(65, 15, n_rows))
    attempts = np.minimum(rng.poisson(4, n_rows), 20)
    completion = clip(rng.beta(2, 2, n_rows) * 100 + 0.3 * (ability - 65))
    spread = 12 / np.sqrt(np.maximum(attempts, 1))
    prev_avg = clip(ability + rng.normal(0, 1, n_rows) * spread)
    last = clip(ability + rng.normal(0, 12, n_rows))
    target = clip(0.75 * ability + 0.15 * completion + 0.6 * np.minimum(attempts, 10) + rng.normal(0, 7, n_rows))

    rows, groups = [], []
    for i in range(n_rows):
        has_history = attempts[i] > 0
        rows.append({
            "prev_quiz_avg": round(float(prev_avg[i]), 2) if has_history else None,
            "prev_attempts": int(attempts[i]),
            "completion_pct": round(float(completion[i]), 2),
            "last_quiz_score": round(float(last[i]), 2) if has_history else None,
        })
        groups.append(f"synthetic-{i // 3}")  # ~3 rows per made-up student
    return rows, [round(float(t), 2) for t in target], groups


def write_csv(rows, targets, groups, path=SYNTHETIC_CSV) -> Path:
    """Save the synthetic rows for inspection; every row says source=synthetic."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(COLUMNS)
        for row, target, group in zip(rows, targets, groups):
            writer.writerow([group, *("" if row[f] is None else row[f] for f in COLUMNS[1:5]), target, "synthetic"])
    return path
