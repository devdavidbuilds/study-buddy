#!/usr/bin/env node
// ==============================================================
// Course catalog audit — READ ONLY.
//
// Classifies every course (duplicates, near-duplicates, placeholder
// content, metadata problems, language/scope questions, dependent
// student/faculty records) and writes:
//   tmp/catalog-audit/audit-<timestamp>.json      full per-course data
//   tmp/catalog-audit/audit-<timestamp>.md        human-readable report
//   tmp/catalog-audit/proposed-removals.json      input for cleanupCatalog.js
//
//   npm run catalog:audit
//
// Nothing in the database is modified.
// ==============================================================

require("dotenv").config({ quiet: true });
const fs = require("fs");
const path = require("path");
const mongoose = require("mongoose");

const OUT_DIR = path.join(__dirname, "..", "tmp", "catalog-audit");

// Generic words ignored when comparing titles for near-duplicates.
const GENERIC = new Set(
  (
    "a an and the for of to in on with your you how from by at is are be it this that learn learning course courses " +
    "complete ultimate guide tutorial tutorials beginner beginners intermediate advanced master mastering masterclass " +
    "introduction intro basics basic fundamentals essentials step steps easy quick simple training class lessons lesson " +
    "part new everything need know 2015 2016 2017 2018 101 zero hero scratch way best fast practical hands"
  ).split(" ")
);

// Lightweight language hints from title words (titles only; descriptions
// were generated by the importer in English). Only used to list titles
// for a scope decision, never as a removal reason.
// Whole-word match that also works next to accented letters.
const words = (list) => new RegExp(`(?<!\\p{L})(${list.join("|")})(?!\\p{L})`, "giu");

const LANG_MARKERS = {
  es: words(["de", "el", "los", "las", "con", "del", "curso", "aprende", "aprender", "desde", "cero", "una", "guitarra", "bolsa", "empresa", "contabilidad", "para", "como", "tu", "fácil", "rápido", "batería", "iníciate"]),
  pt: words(["do", "da", "dos", "das", "em", "seu", "sua", "você", "não", "um", "uma", "de", "aprenda", "financeira", "minhas", "preciso", "organizar", "básico", "violão", "mão", "massa", "jeito", "introdução", "os"]),
  it: words(["il", "della", "delle", "di", "per", "corso", "completo", "tutti", "costruzione", "proposta", "gli", "che"]),
  fr: words(["le", "les", "des", "du", "pour", "avec", "apprendre", "débuter", "à", "marché", "sur"]),
  de: words(["der", "die", "das", "und", "für", "mit", "lernen", "grundlagen", "einführung", "kurs"]),
  en: words(["the", "to", "and", "for", "with", "how", "learn", "your", "in", "of", "from", "beginners", "guide", "course", "complete", "master", "basics", "introduction", "you", "on"]),
};

const normalizeTitle = (value) =>
  String(value || "")
    .normalize("NFKC")
    .toLowerCase()
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .trim();

const titleTokens = (value) =>
  normalizeTitle(value)
    .split(" ")
    .filter((token) => token && !GENERIC.has(token));

const detectLanguage = (title) => {
  if (/[぀-ヿ一-鿿가-힯]/.test(title)) return "ja/zh/ko";
  if (/[Ѐ-ӿ]/.test(title)) return "ru";
  if (/[؀-ۿ]/.test(title)) return "ar";
  const count = (re) => (String(title).match(re) || []).length;
  const en = count(LANG_MARKERS.en);
  const scores = Object.entries(LANG_MARKERS)
    .filter(([lang]) => lang !== "en")
    .map(([lang, re]) => [lang, count(re)])
    .sort((a, b) => b[1] - a[1]);
  const [bestLang, best] = scores[0];
  // Non-English letters (diacritics such as ã, ç, ş, ł) with little English => non-English.
  const foreignLetters = /[à-öø-ÿāăąćčďđēęěğīıįłńňőœřśşšţťūůűųźżž]/iu.test(title);
  if (best >= 2 && best > en) return bestLang;
  if (best >= 1 && en === 0 && /(?<!\p{L})(curso|aprende|para|como|del|los|las)(?!\p{L})/iu.test(title)) return bestLang;
  if (foreignLetters && en < 2) return best > 0 ? bestLang : "other";
  return "en";
};

const jaccard = (a, b) => {
  if (!a.size || !b.size) return 0;
  let shared = 0;
  for (const x of a) if (b.has(x)) shared++;
  return shared / (a.size + b.size - shared);
};

const sourceUrl = (description) => (String(description || "").match(/https?:\/\/\S+/) || [""])[0].replace(/[.,]$/, "");

// A mismatched quote in the source CSV made some titles swallow the
// following columns (",https://www.udemy.com/...,true,115,...").
const CSV_LEAK = /",\s*https?:\/\//i;
const repairTitle = (title) =>
  String(title)
    .split(CSV_LEAK)[0]
    .replace(/'([^']+)$/, "'$1'") // close the quote the CSV broke
    .trim();

const PLACEHOLDER = /introduces the essential principles behind|build confidence through guided practice across/i;

// Engineering departments the Course schema allows; the imported
// non-engineering subjects were mapped onto these arbitrarily.
const SUBJECT_DEPARTMENT_OK = {
  "Web Development": ["CSE", "IT"],
};

const main = async () => {
  await mongoose.connect(process.env.MONGODB_URI);
  const db = mongoose.connection.db;

  const courses = await db
    .collection("courses")
    .find(
      {},
      {
        projection: {
          courseName: 1, courseCode: 1, category: 1, level: 1, department: 1, semester: 1, description: 1,
          duration: 1, students: 1, rating: 1, reviewsCount: 1, faculty: 1, status: 1, contentMeta: 1,
          createdAt: 1, updatedAt: 1,
          lessonCount: { $sum: { $map: { input: "$modules", in: { $size: "$$this.lessons" } } } },
          moduleCount: { $size: "$modules" },
          placeholderLessons: {
            $sum: {
              $map: {
                input: "$modules",
                in: {
                  $size: {
                    $filter: {
                      input: "$$this.lessons",
                      cond: { $regexMatch: { input: { $ifNull: ["$$this.content", ""] }, regex: PLACEHOLDER.source, options: "i" } },
                    },
                  },
                },
              },
            },
          },
        },
      }
    )
    .toArray();

  // Dependent records per course (anything a removal could orphan).
  const countBy = async (collection, field) => {
    const rows = await db.collection(collection).aggregate([{ $group: { _id: `$${field}`, n: { $sum: 1 } } }]).toArray();
    return new Map(rows.map((r) => [String(r._id), r.n]));
  };
  const [progressBy, quizBy, assignmentBy, activityBy, jobBy] = await Promise.all([
    countBy("courseprogresses", "course"),
    countBy("quizzes", "course"),
    countBy("assignments", "course"),
    countBy("studentactivities", "course"),
    countBy("contentgenerationjobs", "course"),
  ]);
  const facultyUsers = new Map(
    (await db.collection("users").find({}, { projection: { fullName: 1, email: 1, role: 1 } }).toArray()).map((u) => [String(u._id), u])
  );

  const records = courses.map((c) => {
    const id = String(c._id);
    const dependents = {
      progress: progressBy.get(id) || 0,
      quizzes: quizBy.get(id) || 0,
      assignments: assignmentBy.get(id) || 0,
      activity: activityBy.get(id) || 0,
      contentJobs: jobBy.get(id) || 0,
    };
    const owner = facultyUsers.get(String(c.faculty));
    const issues = [];
    const letters = (String(c.courseName).match(/\p{L}/gu) || []).length;

    if (letters < 3) issues.push("meaningless-title");
    if (CSV_LEAK.test(c.courseName)) issues.push("corrupted-title");
    if (!c.description || String(c.description).trim().length < 10) issues.push("missing-description");
    if (/udemy\.com/i.test(c.description || "")) issues.push("description-links-to-source-site");
    if (c.lessonCount === 0) issues.push("no-lessons");
    else if (c.lessonCount < 3) issues.push("too-few-lessons");
    if (c.lessonCount > 120) issues.push("implausible-lesson-count");
    if (c.placeholderLessons > 0) issues.push("placeholder-lesson-content");
    if (!(SUBJECT_DEPARTMENT_OK[c.category] || []).includes(c.department)) issues.push("department-does-not-match-subject");
    if (/\b(\d{2,}) months\b/.test(c.duration || "") || /\b([7-9]|1\d) months\b/.test(c.duration || "")) issues.push("implausible-duration");
    if (!owner) issues.push("faculty-owner-missing");
    else if (owner.role !== "faculty" && owner.role !== "admin") issues.push("owner-is-not-faculty");

    return {
      id,
      courseCode: c.courseCode,
      title: c.courseName,
      category: c.category,
      level: c.level,
      department: c.department,
      language: detectLanguage(c.courseName),
      students: c.students || 0,
      reviews: c.reviewsCount || 0,
      rating: c.rating || 0,
      lessons: c.lessonCount,
      modules: c.moduleCount,
      placeholderLessons: c.placeholderLessons,
      enriched: Boolean(c.contentMeta),
      sourceUrl: sourceUrl(c.description),
      owner: owner ? `${owner.fullName} <${owner.email}>` : null,
      dependents,
      hasDependents: Object.values(dependents).some(Boolean),
      issues,
      ...(CSV_LEAK.test(c.courseName) ? { repairedTitle: repairTitle(c.courseName) } : {}),
    };
  });

  const byId = new Map(records.map((r) => [r.id, r]));

  // ---- 1. Exact duplicates: same source course (URL) imported twice ----
  const byUrl = new Map();
  records.forEach((r) => r.sourceUrl && (byUrl.get(r.sourceUrl) || byUrl.set(r.sourceUrl, []).get(r.sourceUrl)).push(r));
  const exactDuplicateGroups = [...byUrl.values()].filter((g) => g.length > 1);

  // ---- 2. Same-title duplicates: identical normalized title, different source course ----
  const byTitle = new Map();
  records.forEach((r) => {
    const key = `${r.category}::${normalizeTitle(r.title)}`;
    (byTitle.get(key) || byTitle.set(key, []).get(key)).push(r);
  });
  const sameTitleGroups = [...byTitle.values()].filter((g) => g.length > 1);

  // ---- 3. Near-duplicates: very similar distinctive title words, same category & language ----
  const nearPairs = [];
  const sameTitleIds = new Set(sameTitleGroups.flat().map((r) => r.id));
  const byCategory = new Map();
  records.forEach((r) => (byCategory.get(r.category) || byCategory.set(r.category, []).get(r.category)).push(r));
  for (const list of byCategory.values()) {
    const prepared = list.map((r) => ({ r, tokens: new Set(titleTokens(r.title)) })).filter((x) => x.tokens.size >= 2);
    for (let i = 0; i < prepared.length; i++) {
      for (let j = i + 1; j < prepared.length; j++) {
        const a = prepared[i];
        const b = prepared[j];
        if (a.r.language !== b.r.language) continue;
        if (normalizeTitle(a.r.title) === normalizeTitle(b.r.title)) continue; // already in same-title groups
        const score = jaccard(a.tokens, b.tokens);
        if (score >= 0.8) nearPairs.push({ a: a.r, b: b.r, score: Math.round(score * 100) / 100 });
      }
    }
  }

  // ---- Proposed removals: weaker members of same-title groups ----
  // "Better" = more enrolled students, then more reviews, then rating.
  const rank = (r) => [r.students, r.reviews, r.rating];
  const better = (x, y) => {
    const [a, b] = [rank(x), rank(y)];
    for (let i = 0; i < a.length; i++) if (a[i] !== b[i]) return a[i] > b[i] ? x : y;
    return x.courseCode < y.courseCode ? x : y;
  };

  const proposals = [];
  const manualReview = [];

  for (const group of [...exactDuplicateGroups, ...sameTitleGroups]) {
    const keep = group.reduce(better);
    for (const r of group) {
      if (r === keep) continue;
      const isExact = exactDuplicateGroups.includes(group);
      const reason = isExact
        ? `Exact duplicate import of the same source course as ${keep.courseCode}.`
        : `Same title as ${keep.courseCode} "${keep.title}" in ${r.category}; keeping the one with more students/reviews (${keep.students} students, ${keep.reviews} reviews vs ${r.students}/${r.reviews}). Both have only auto-generated placeholder lessons, so no learning material is lost.`;
      const entry = {
        id: r.id,
        courseCode: r.courseCode,
        title: r.title,
        category: r.category,
        level: r.level,
        students: r.students,
        reviews: r.reviews,
        lessons: r.lessons,
        keepInstead: { id: keep.id, courseCode: keep.courseCode, title: keep.title },
        reason,
        dependents: r.dependents,
        type: isExact ? "exact-duplicate" : "same-title-duplicate",
      };
      if (r.hasDependents || r.enriched) {
        manualReview.push({ ...entry, reviewReason: r.enriched ? "has enriched content" : "has student/faculty records" });
      } else {
        proposals.push(entry);
      }
    }
  }

  const zeroLessonSource = records.filter((r) => r.issues.includes("no-lessons") || r.issues.includes("too-few-lessons"));
  for (const r of zeroLessonSource) {
    manualReview.push({
      id: r.id, courseCode: r.courseCode, title: r.title, category: r.category, lessons: r.lessons,
      dependents: r.dependents, type: "no-real-material",
      reviewReason: "Source course had no/too few lectures; the topic is legitimate, so repair (enrich) is preferred over removal.",
    });
  }
  for (const r of records.filter((x) => x.issues.includes("meaningless-title"))) {
    manualReview.push({ id: r.id, courseCode: r.courseCode, title: r.title, category: r.category, dependents: r.dependents, type: "meaningless-title", reviewReason: "Title has fewer than 3 letters." });
  }

  const repairs = records
    .filter((r) => r.repairedTitle)
    .map((r) => ({ id: r.id, courseCode: r.courseCode, field: "courseName", from: r.title, to: r.repairedTitle, reason: "CSV columns leaked into the title during import." }));

  // Scope questions: not proposed for removal, decided by the owner.
  const languages = {};
  records.forEach((r) => (languages[r.language] = (languages[r.language] || 0) + 1));
  const nonEnglish = records.filter((r) => r.language !== "en");

  const issueCounts = {};
  records.forEach((r) => r.issues.forEach((i) => (issueCounts[i] = (issueCounts[i] || 0) + 1)));
  const categoryCounts = {};
  records.forEach((r) => (categoryCounts[r.category] = (categoryCounts[r.category] || 0) + 1));

  const protectedCourses = records.filter((r) => r.hasDependents);
  const proposedIds = new Set(proposals.map((p) => p.id));
  const reviewIds = new Set(manualReview.map((m) => m.id));
  const retained = records.filter((r) => !proposedIds.has(r.id) && !reviewIds.has(r.id));

  const summary = {
    generatedAt: new Date().toISOString(),
    totalCourses: records.length,
    categories: categoryCounts,
    levels: records.reduce((m, r) => ((m[r.level] = (m[r.level] || 0) + 1), m), {}),
    languages,
    exactDuplicateGroups: exactDuplicateGroups.length,
    sameTitleGroups: sameTitleGroups.length,
    sameTitleCourses: sameTitleGroups.reduce((n, g) => n + g.length, 0),
    nearDuplicatePairs: nearPairs.length,
    issueCounts,
    coursesWithDependents: protectedCourses.length,
    proposedRemovals: proposals.length,
    proposedTitleRepairs: repairs.length,
    manualReview: manualReview.length,
    retained: retained.length,
  };

  fs.mkdirSync(OUT_DIR, { recursive: true });
  const stamp = new Date().toISOString().replace(/[:.]/g, "-");
  const jsonFile = path.join(OUT_DIR, `audit-${stamp}.json`);
  const mdFile = path.join(OUT_DIR, `audit-${stamp}.md`);
  const proposalFile = path.join(OUT_DIR, "proposed-removals.json");

  fs.writeFileSync(
    jsonFile,
    JSON.stringify({ summary, proposals, repairs, manualReview, sameTitleGroups: sameTitleGroups.map((g) => g.map((r) => r.id)), nearPairs: nearPairs.map((p) => ({ a: p.a.id, b: p.b.id, score: p.score })), protected: protectedCourses, records }, null, 2)
  );
  fs.writeFileSync(
    proposalFile,
    JSON.stringify(
      {
        generatedAt: summary.generatedAt,
        note: "Proposed only. Nothing is removed until you approve: copy the entries you approve into an approved list and run cleanupCatalog.js.",
        courses: proposals.map((p) => ({ id: p.id, courseCode: p.courseCode, title: p.title, reason: p.reason, keepInstead: p.keepInstead.courseCode })),
        titleRepairs: repairs,
      },
      null,
      2
    )
  );

  // ---- Markdown report ----
  const lines = [];
  const row = (cells) => lines.push(`| ${cells.map((c) => String(c ?? "").replace(/\|/g, "\\|")).join(" | ")} |`);
  lines.push(`# Course catalog audit`, "", `Generated ${summary.generatedAt}. Read-only: no data was modified.`, "");
  lines.push("## Summary", "");
  row(["Metric", "Value"]);
  row(["---", "---"]);
  row(["Total courses", summary.totalCourses]);
  Object.entries(categoryCounts).forEach(([k, v]) => row([`Category: ${k}`, v]));
  row(["Exact duplicate imports (same source URL)", summary.exactDuplicateGroups]);
  row(["Same-title duplicate groups / courses", `${summary.sameTitleGroups} / ${summary.sameTitleCourses}`]);
  row(["Near-duplicate title pairs (manual review)", summary.nearDuplicatePairs]);
  row(["Courses with student/faculty records (protected)", summary.coursesWithDependents]);
  row(["Proposed removals", summary.proposedRemovals]);
  row(["Proposed title repairs", summary.proposedTitleRepairs]);
  row(["Manual review", summary.manualReview]);
  row(["Retained", summary.retained]);
  lines.push("", "### Issues found (repairable, not removal reasons)", "");
  row(["Issue", "Courses"]);
  row(["---", "---"]);
  Object.entries(issueCounts).sort((a, b) => b[1] - a[1]).forEach(([k, v]) => row([k, v]));
  lines.push("", "### Title language (heuristic)", "");
  row(["Language", "Courses"]);
  row(["---", "---"]);
  Object.entries(languages).forEach(([k, v]) => row([k, v]));

  lines.push("", "## Proposed removals", "");
  row(["Course code", "Title", "Category", "Students", "Keep instead", "Reason"]);
  row(["---", "---", "---", "---", "---", "---"]);
  proposals.forEach((p) => row([p.courseCode, p.title, p.category, p.students, p.keepInstead.courseCode, p.reason]));

  lines.push("", "## Proposed title repairs (corrupted by CSV import)", "");
  row(["Course code", "Current title", "Repaired title"]);
  row(["---", "---", "---"]);
  repairs.forEach((r) => row([r.courseCode, r.from, r.to]));

  lines.push("", "## Manual review", "");
  row(["Course code", "Title", "Type", "Dependents", "Why review"]);
  row(["---", "---", "---", "---", "---"]);
  manualReview.forEach((m) => row([m.courseCode, m.title, m.type, JSON.stringify(m.dependents), m.reviewReason]));

  lines.push("", "## Courses with student/faculty records (never removed without explicit approval)", "");
  row(["Course code", "Title", "Progress", "Quizzes", "Assignments", "Activity"]);
  row(["---", "---", "---", "---", "---", "---"]);
  protectedCourses.forEach((r) => row([r.courseCode, r.title, r.dependents.progress, r.dependents.quizzes, r.dependents.assignments, r.dependents.activity]));

  lines.push("", "## Near-duplicate title pairs (not proposed — distinct courses with similar titles)", "");
  row(["Course A", "Course B", "Similarity"]);
  row(["---", "---", "---"]);
  nearPairs.slice(0, 200).forEach((p) => row([`${p.a.courseCode} ${p.a.title}`, `${p.b.courseCode} ${p.b.title}`, p.score]));

  lines.push("", `## Non-English titles (${nonEnglish.length}) — scope decision, not proposed`, "");
  row(["Course code", "Title", "Language", "Category"]);
  row(["---", "---", "---", "---"]);
  nonEnglish.forEach((r) => row([r.courseCode, r.title, r.language, r.category]));

  fs.writeFileSync(mdFile, lines.join("\n"));

  console.log(JSON.stringify(summary, null, 2));
  console.log(`\nReport:    ${path.relative(process.cwd(), mdFile)}`);
  console.log(`Data:      ${path.relative(process.cwd(), jsonFile)}`);
  console.log(`Proposals: ${path.relative(process.cwd(), proposalFile)}`);
};

main()
  .catch((error) => {
    console.error(`Error: ${error.message}`);
    process.exitCode = 1;
  })
  .finally(() => mongoose.disconnect());
