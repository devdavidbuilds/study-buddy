export function getStarterCode(item, language) {
  if (!item) return '';
  if (item.kind === 'program') {
    if (item.language === language) return item.code;
    const comment = language === 'python' ? '#' : '//';
    return `${comment} "${item.title}" is a ${languageLabel(item.language)} sample program.\n${comment} Switch the language back to ${languageLabel(item.language)} to run it.\n`;
  }
  return item.templates?.[language] || '';
}
